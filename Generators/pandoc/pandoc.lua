-- This file contains custom LUA filters for Pandoc.

if FORMAT:match 'latex' then
--[[
  Handle GitHub Alert Divs generated by the "alerts" extension in Pandoc.
  % pandoc -f markdown+alerts -t native
  > [!TIP]
  > A suggestion.
  ^D
  [ Div
      ( "" , [ "tip" ] , [] )
      [ Div ( "" , [ "title" ] , [] ) [ Para [ Str "Tip" ] ]
      , Para [ Str "A" , Space , Str "suggestion." ]
      ]
  ]
]]
  function Div(div)
    local env_name = nil

    -- Check if the Div has one of the alert classes
    for _, div_class in ipairs(div.classes or {}) do
      if div_class == "note"
        or div_class == "tip"
        or div_class == "important"
        or div_class == "warning"
        or div_class == "caution" then
        -- Select the target LaTeX environment for the alert kind.
        env_name = div_class .. "-box"
        break
      end
    end

    if not env_name then
      -- Not an alert Div, so keep it unchanged.
      return nil
    end

    local body_blocks = {}

    -- Remove the generated title block and keep the remaining blocks as body content.
    for _, block in ipairs(div.content) do
      local is_title_div = block.t == "Div"
        and block.classes
        and block.classes[1] == "title"

      if not is_title_div then
        table.insert(body_blocks, block)
      end
    end

    if #body_blocks == 0 then
      -- No content blocks found in the alert Div, so keep it unchanged.
      return nil
    end

    return {
      pandoc.RawBlock("latex", "\\begin{" .. env_name .. "}"),
      table.unpack(body_blocks),
      pandoc.RawBlock("latex", "\\end{" .. env_name .. "}")
    }
  end

  -- Wrap left/right aligned images in the floatingfigure environment for LaTeX output.
  function Image(img)
    -- Apply image alignment.
    if img.attributes.align == "left" or img.attributes.align == "right" then
      -- The option is either 'l' or 'r'.
      local floatfltOption = img.attributes.align:sub(1, 1)
      
      -- Get the actual image width.
      local imageWidth = img.attributes.width

      -- Wrap the image in a floatingfigure environment.
      return {
        pandoc.RawInline('latex', '\\begin{floatingfigure}[' .. floatfltOption .. ']{' .. imageWidth .. '}'),
        img,
        pandoc.RawInline('latex', '\\end{floatingfigure}')
      }
    end
  end

  -- Convert inline HTML line breaks to Pandoc-native line breaks in LaTeX output.
  function RawInline (el)
    -- Transform inline HTML `<br>` elements into format-indepentent line breaks.
    if el.format:match '^html' and el.text:match '%<br ?/?%>' then
      return pandoc.LineBreak()
    end
  end
end
